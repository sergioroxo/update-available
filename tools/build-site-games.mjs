#!/usr/bin/env node
/**
 * THE GAMES ON THE ERA WEBSITES — each year's game, built from the piece's own code into one script beside its page.
 *
 *     node tools/build-site-games.mjs            # → public/sites/{1997,2003,2016,2026}/game.js
 *     node tools/build-site-games.mjs --check    # builds in memory and fails if a file on disk is stale
 *     node tools/build-site-games.mjs --sizes    # prints each script's size (raw and gzipped)
 *
 * `node tools/gen_era_sites.mjs` runs this too (and `--check` with its own `--check`), so `npm run gen-sites` writes the
 * pages and their games together and `npm test` (check-era-sites.mjs) fails when either is stale.
 *
 * ⚑ WHY (S400, UiB job 29 Part C; his 16 Nov: "They are Optional, you are not supposed to play the game in 2026, it is
 * just a suggestion of Lamby … also we should add all the games in the Close HTML's"). The four games are self-contained
 * classes (src/games/*.ts draw only with fillStyle + fillRect; FloppySheep with a 2D context) that know nothing of the
 * room, so a page can run the SAME code: esbuild bundles each with its data and theme into one plain script (an IIFE,
 * no modules, no imports at run time). What the piece gives them and a page cannot — the frame's one mute, the mixer, the
 * session's motion setting, the sound registry — is swapped at build time for the small modules in src/sitegames/shims/.
 * The host is src/sitegames/shell.ts. Design and costs: docs/reinterp/SITE_GAMES_NOTE_2026-11-17.md.
 *
 * The output is deterministic (same sources, same esbuild → same bytes), minified, and carries a header saying what it
 * is and where it came from. check-era-sites.mjs reads it for any network or storage API.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, relative, dirname } from 'node:path';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** each year's game: its page folder, its entry (src/sitegames/), and the room's own code it carries */
export const SITE_GAMES = [
  { year: '1997', id: 'fitin', name: 'FIT IN', entry: 'src/sitegames/fitin.ts', from: 'src/games/fitIn.ts' },
  { year: '2003', id: 'clear', name: 'CLEAR', entry: 'src/sitegames/clear.ts', from: 'src/games/clear.ts' },
  { year: '2016', id: 'floppysheep', name: 'FloppySheep', entry: 'src/sitegames/floppysheep.ts', from: 'src/desktop/apps/floppysheep.ts' },
  { year: '2026', id: 'matchmade', name: 'MATCH MADE SIMPLE', entry: 'src/sitegames/matchmade.ts', from: 'src/games/matchMade.ts' }
];

/** the piece's modules a page has no use for, and what stands in for each (src/sitegames/shims/) */
const SHIMS = new Map([
  ['src/state/gameMenuBus.ts', 'src/sitegames/shims/gameMenuBus.ts'],
  ['src/audio/mix.ts', 'src/sitegames/shims/mix.ts'],
  ['src/state/motion.ts', 'src/sitegames/shims/motion.ts'],
  ['src/audio/tapeAudio.ts', 'src/sitegames/shims/tapeAudio.ts']
].map(([a, b]) => [join(ROOT, a), join(ROOT, b)]));

/** a data file's working notes (`_doc`, `_docV7`, … — keys that start with `_`) are for the people who edit it, never
 *  read by a game, and they do not go out on a public page: dropped at build, at every depth */
const stripNotes = (v) => Array.isArray(v) ? v.map(stripNotes)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, stripNotes(x)]))
  : v;

const shimPlugin = {
  name: 'site-game-shims',
  setup(b) {
    b.onResolve({ filter: /^\.\.?\// }, (args) => {
      if (args.kind === 'entry-point') return undefined;
      const base = resolve(args.resolveDir, args.path);
      for (const p of [base, `${base}.ts`]) if (SHIMS.has(p)) return { path: SHIMS.get(p) };
      return undefined;
    });
    b.onLoad({ filter: /\.json$/ }, (args) => ({ contents: JSON.stringify(stripNotes(JSON.parse(readFileSync(args.path, 'utf8')))), loader: 'json' }));
  }
};

const banner = (g) => `/* ${g.name} — the ${g.year} era website's game (YOUR UPDATE HAS FAILED, SurvivingSOGICE, University of Bergen).
 * Generated by tools/build-site-games.mjs from the piece's own code (${g.from}, host ${g.entry}). Do not edit by hand.
 * It draws on this page's canvas and plays sound made live in your browser. It sends nothing, loads nothing from
 * elsewhere and stores nothing. Source and licence: the project's repository. */`;

/** build one game in memory; returns the script's text */
export async function buildOne(g) {
  const out = await build({
    entryPoints: [join(ROOT, g.entry)], absWorkingDir: ROOT, bundle: true, write: false,
    format: 'iife', platform: 'browser', target: 'es2020', minify: true, legalComments: 'none', charset: 'utf8',
    loader: { '.json': 'json' }, plugins: [shimPlugin], banner: { js: banner(g) },
    define: { __FESTIVAL__: 'false', __BUILD_TAG__: '"site"', __APP_VERSION__: '"site"', __BUILD_COMMIT__: '"site"', __BUILD_DATE__: '"site"' },
    logLevel: 'silent'
  });
  return out.outputFiles[0].text;
}

export const outPath = (g) => join(ROOT, 'public/sites', g.year, 'game.js');

/** write (or, with check, compare) every game; returns the stale paths (check) or the written ones */
export async function buildSiteGames({ check = false } = {}) {
  const touched = [];
  for (const g of SITE_GAMES) {
    const js = await buildOne(g);
    const p = outPath(g);
    if (check) { if (!existsSync(p) || readFileSync(p, 'utf8') !== js) touched.push(relative(ROOT, p)); }
    else { writeFileSync(p, js); touched.push(relative(ROOT, p)); }
  }
  return touched;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes('--check')) {
    const stale = await buildSiteGames({ check: true });
    if (stale.length) { console.error(`site games STALE (run: node tools/gen_era_sites.mjs): ${stale.join(', ')}`); process.exit(1); }
    console.log(`site games fresh: ${SITE_GAMES.length} scripts match the piece's code`);
  } else if (args.includes('--sizes')) {
    for (const g of SITE_GAMES) {
      const js = await buildOne(g);
      const raw = Buffer.byteLength(js), gz = gzipSync(js).length;
      console.log(`${g.year} ${g.name.padEnd(18)} ${(raw / 1024).toFixed(1).padStart(6)} KB  (${(gz / 1024).toFixed(1)} KB gzipped)`);
    }
  } else {
    const wrote = await buildSiteGames();
    console.log(`wrote ${wrote.join(', ')}`);
  }
}
